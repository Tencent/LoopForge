func conversationApprovalLaunch(executionRoot string, arguments ...string) (string, error) {
	codex := len(arguments) == 1 && arguments[0] == "codex"
	if filepath.VolumeName(executionRoot) == "" {
		if codex {
			arguments = nil // a Linux container retains the existing hook protocol
		}
		return posixConversationApprovalLaunch(executionRoot, arguments...), nil
	}
	return windowsConversationApprovalScriptLaunch(path.Join(filepath.ToSlash(executionRoot), "native-approval.py"), codex, false, arguments...)
}

func windowsConversationApprovalScriptLaunch(scriptPath string, codex, platformGuard bool, arguments ...string) (string, error) {
	ctx, cancel := context.WithTimeout(context.Background(), 5*time.Second)
	defer cancel()
	python, err := conversationApprovalPythonExecutable(ctx)
	if err != nil {
		return "", err
	}
	if _, err := exec.LookPath("powershell.exe"); err != nil {
		return "", fmt.Errorf("native approval hooks require Windows PowerShell: %w", err)
	}
	quote := func(value string) string { return "'" + strings.ReplaceAll(value, "'", "''") + "'" }
	// A quote-free outer command runs under native hook shells. Only the
	// encoded PowerShell source parses executable and script paths.
	// Explicit UTF-8 preserves exact tool input and hook JSON on Windows 5.1.
	invoke := "& " + quote(python) + " -I -X utf8 " + quote(scriptPath)
	for _, argument := range arguments {
		invoke += " " + quote(argument)
	}
	script := "$ErrorActionPreference='Stop';[Console]::InputEncoding=[Text.UTF8Encoding]::new($false);[Console]::OutputEncoding=[Text.UTF8Encoding]::new($false);$OutputEncoding=[Console]::OutputEncoding;"
	if codex {
		// Codex's Windows PowerShell hook shell maps a child's exit 2 to 1.
		// Exit 1 ignores stdout; structured JSON on exit 0 enforces denial.
		// The launcher itself also denies when Python or the script cannot run.
		denial := `{"hookSpecificOutput":{"hookEventName":"PreToolUse","permissionDecision":"deny","permissionDecisionReason":"Native approval hook could not run."}}`
		allowedCodes, allowedOutput := "$code -eq 0", "$text.Trim() -eq '{}'"
		if platformGuard {
			allowedCodes = "($code -eq 0 -or $code -eq 2)"
			allowedOutput = "($text.Trim() -eq '{}' -or [string]::IsNullOrWhiteSpace($text))"
		}
		script += "try{$result=" + invoke + " 2>$null;$code=$LASTEXITCODE;$text=($result -join [Environment]::NewLine);if(-not(" + allowedCodes + ")){throw 'hook failed'};if($code -eq 0 -and " + allowedOutput + "){[Console]::Out.WriteLine('{}')}else{$parsed=$text|ConvertFrom-Json;if($parsed.hookSpecificOutput.hookEventName -ne 'PreToolUse' -or $parsed.hookSpecificOutput.permissionDecision -ne 'deny' -or $parsed.hookSpecificOutput.permissionDecisionReason -isnot [string] -or [string]::IsNullOrWhiteSpace($parsed.hookSpecificOutput.permissionDecisionReason)){throw 'invalid hook response'};[Console]::Out.WriteLine($text)}}catch{[Console]::Out.WriteLine(" + quote(denial) + ")};exit 0"
	} else {
		script += "try{" + invoke + ";if($LASTEXITCODE -ne 0){exit 2};exit 0}catch{[Console]::Error.WriteLine('Native approval hook could not run.');exit 2}"
	}
	encoded := utf16.Encode([]rune(script))
	raw := make([]byte, len(encoded)*2)
	for i, word := range encoded {
		binary.LittleEndian.PutUint16(raw[i*2:], word)
	}
	return "powershell.exe -NoProfile -NonInteractive -ExecutionPolicy Bypass -EncodedCommand " + base64.StdEncoding.EncodeToString(raw), nil
}

// Only the two platform-owned Codex guard assets are adapted. Their Python
// policy and the command's other arguments, credentials and MCP URLs remain
// authoritative; a native-approval hook must not replace a platform guard.
func adaptPlatformConversationApproval(root string, command CommandSpec) (CommandSpec, error) {
	if command.Provider != "codex" {
		return command, nil
	}
	for i, argument := range command.Argv {
		if !strings.HasPrefix(argument, "hooks.PreToolUse=") {
			continue
		}
		for _, name := range []string{"codex-native-guard.py", "guard.py"} {
			guard := filepath.Join(root, name)
			guardPath := filepath.ToSlash(guard)
			// Match the complete serialized command generated by the platform,
			// rather than an unrelated user hook mentioning the same file name.
			quoted := "command=" + strconv.Quote("python3 "+strconv.Quote(guardPath))
			legacy := "command=" + strconv.Quote("python3 "+shellSingleQuote(guardPath))
			if !strings.Contains(argument, quoted) && !strings.Contains(argument, legacy) {
				continue
			}
			info, err := os.Lstat(guard)
			if err != nil || !info.Mode().IsRegular() {
				return command, fmt.Errorf("platform Codex guard is unavailable: %s", name)
			}
			launch, err := windowsConversationApprovalScriptLaunch(filepath.ToSlash(guard), true, true)
			if err != nil {
				return command, err
			}
			command.Argv = append([]string(nil), command.Argv...)
			original := quoted
			if !strings.Contains(argument, original) {
				original = legacy
			}
			command.Argv[i] = strings.Replace(argument, original, "command="+strconv.Quote(launch), 1)
			return command, nil
		}
	}
	return command, nil
}

func conversationApprovalFailureGuard(executionRoot, launch string) string {
	if filepath.VolumeName(executionRoot) != "" {
		return launch // the native launcher converts interpreter failures to denial
	}
	return launch + " || exit 2"
}

func checkConversationApprovalRuntime(ctx context.Context) error {
	_, err := conversationApprovalPythonExecutable(ctx)
	return err
}

func conversationApprovalPythonExecutable(ctx context.Context) (string, error) {
	for _, name := range []string{"python.exe", "python3.exe"} {
		binary, err := exec.LookPath(name)
		if err != nil || strings.Contains(strings.ToLower(filepath.ToSlash(binary)), "/microsoft/windowsapps/") {
			continue // App Execution Aliases may open the Store instead of Python
		}
		checkCtx, cancel := context.WithTimeout(ctx, 2*time.Second)
		err = exec.CommandContext(checkCtx, binary, "-I", "-X", "utf8", "-c", "import sys,json,urllib.request;assert sys.version_info >= (3,8)").Run()
		cancel()
		if err == nil {
			return binary, nil
		}
	}
	return "", fmt.Errorf("native approval hooks require Python 3.8 or newer; install Python and add python.exe to the Runner account's PATH")
}
